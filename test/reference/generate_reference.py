"""Write test/reference/peoc_reference.toml from a PEOC model dump.

The dump is made by peoc_py3/verification/dump_model.py (one .npy file per model
quantity) on the reference stack: PEOC 1.0 under Python 2.7, numpy 1.16.5,
OpenBLAS 0.3.12.  This script needs only numpy:

    python3 generate_reference.py <dump_dir> > peoc_reference.toml

Indices are written 1-based and in Julia's (x, y, year) order.
"""
import sys
import numpy as np

d = sys.argv[1]
load = lambda name: np.load('%s/%s.npy' % (d, name))
out = []
w = out.append


def num(x):
    return repr(float(x))


w('# Generated by generate_reference.py from a dump of PEOC 1.0 (Python 2.7,')
w('# numpy 1.16.5, OpenBLAS 0.3.12).  Indices are 1-based, (x, y, year).')
w('')
w('[data]')
for name in ['H', 'T', 'ash_density', 'infection_1', 'infection_2']:
    a = load(name)
    w('%s_sum = %s' % (name, num(np.sum(a, dtype=np.float64))))
    w('%s_nonzero = %d' % (name, np.count_nonzero(a)))
# probe cells: exact values at the largest entries and a few fixed cells
for name in ['H', 'T', 'ash_density', 'infection_1', 'infection_2']:
    a = load(name)
    flat = np.argsort(a, axis=None)[-3:]
    probes = [np.unravel_index(i, a.shape) for i in flat]
    probes.append(tuple(s // 2 for s in a.shape))
    rows = []
    for p in probes:
        jl = list(p[1:]) + [p[0]] if a.ndim == 3 else list(p)
        rows.append('[%s, %s]' % (', '.join(str(i + 1) for i in jl), num(a[p])))
    w('%s_probes = [%s]' % (name, ', '.join(rows)))
w('')
w('[observations]')
counts, visits, props, logc = [], [], [], []
for k in range(16):
    o = load('observation_%02d' % k)
    c = load('clb_likeli_%02d' % k)
    counts.append(str(o.shape[1]))
    visits.append(str(int(o[3].sum())))
    props.append(num(o[2].sum()))
    logc.append(num(c[:, 0].sum()))
w('years = [%s]' % ', '.join(str(2008 + k) for k in range(16)))
w('quadrats = [%s]' % ', '.join(counts))
w('visits = [%s]' % ', '.join(visits))
w('proportion_sum = [%s]' % ', '.join(props))
w('log_choose_sum = [%s]' % ', '.join(logc))
o = load('observation_00')
w('first_2008 = [%d, %d, %s, %d]' % (o[0, 0] + 1, o[1, 0] + 1, num(o[2, 0]), o[3, 0]))
w('')
w('[loglikelihood]')
w('parameters = [')
w('  [1000.0, 15.0, 0.001, 0.0001, 30.0, 60.0, 40.0, 0.01, 0.002, 0.01],')
w('  [1000.0, 0.0, 30.0, 0.0, 20.0, 90.0, 22.0, 1.0, 0.0085, 0.1],')
w('  [1000.0, 50.0, 40.0, 2.0, 25.0, 80.0, 30.0, 0.5, 0.01, 0.5],')
w(']')
ll = load('loglik')
w('value = [%s]' % ', '.join(num(v) for v in ll[:, 0]))
w('zero = [%s]' % ', '.join('true' if v else 'false' for v in ll[:, 1]))
w('')
w('# fungi per ash (12 years) for the third parameter set')
w('[fungi]')
F = load('fungi')
pos = F[F > 0]
w('sum = %s' % num(F.sum()))
w('positive = %d' % pos.size)
w('min_positive = %s' % num(pos.min()))
probes = []
for yr in [2, 6, 11]:
    a = F[yr]
    p = a[a > 0]
    for q in [0.0, 1e-4, 0.01, 0.5, 1.0]:  # tails included
        v = np.quantile(p, q, method='lower') if hasattr(np, 'quantile') else None
        idx = np.argwhere(a == v)[0]
        probes.append('[%d, %d, %d, %s]' % (idx[0] + 1, idx[1] + 1, yr + 1, num(v)))
w('probes = [%s]' % ', '.join(probes))
print('\n'.join(out))
