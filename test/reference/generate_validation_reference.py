"""Write test/reference/peoc_validation.toml with the Python 3 port of PEOC.

The port's outputs are verified identical to PEOC 1.0's (see its verification/ folder).
Covers the RMSE of action 5 at the paper's theta_max, a small grid from action 8, and a short
AMIS run from action 2, so that its draws and likelihoods can be replayed in Julia:

    <peoc_py3 dir>/.venv/bin/python generate_validation_reference.py <peoc_py3 dir> > peoc_validation.toml
"""
import os
import re
import shutil
import subprocess
import sys
import numpy as np

code = os.path.abspath(sys.argv[1])
py = os.path.join(code, '.venv', 'bin', 'python')
THETA_MAX = [1000.0, 0.0, 23.26, 0.0, 18.51, 92.0, 21.50001, 1.0, 0.00855, 0.056]
env = dict(os.environ, MPLBACKEND='Agg', OPENBLAS_NUM_THREADS='1')
INIT = '[1000.,0.,24.,0.,18.,90.,21.50001,1.,0.0085,0.05]'
RANGES = ('np.array([[1000.,1000.],[0.,0.],[0.,800.],[0.,0.],[0.,200.],[0.,500.],'
          '[21.50001,21.50001],[1.,1.],[0.,200.],[0.,10.]])')


def run(*args):
    r = subprocess.run([py, 'run.py'] + list(args), cwd=code, env=env, text=True,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if r.returncode != 0:
        sys.exit(r.stdout)
    return r.stdout


def path(name):
    return os.path.join(code, 'Simulations', name)


def num(x):
    return repr(float(x))


def vec(a):
    return '[' + ', '.join(num(x) for x in np.ravel(a)) + ']'


def clean(name):
    shutil.rmtree(path(name), ignore_errors=True)


out = ['# Generated by generate_validation_reference.py from the Python 3 port of PEOC.', '']
for name in ('_ref_rmse', '_ref_grid', '_ref_amis'):
    clean(name)

# Action 5 at theta_max: a one-sample "MH run" holding only that parameter set
run('mh', '--run-dir', 'Simulations/_ref_rmse', '--solver', 'fast', '--config-set', 'N_MH=1',
    '--config-set', 'initial_parameters=%r' % THETA_MAX)
np.save(path('_ref_rmse/sampled_parameters.npy'), np.array([THETA_MAX]))
np.save(path('_ref_rmse/log_likelihood.npy'), np.array([-1.0]))
text = run('rmse', '_ref_rmse', '--solver', 'exact')
rows = re.findall(r'year\s+(\d+)\s*:\s*(\d+)\s+(\S+)\s+(\S+)', text)
ll = re.search(r'Log-likelihood from 2008 to (\d+)\s*:\s*(\S+)', text)
assert len(rows) == 16 and ll.group(1) == '2023', text
out += ['[rmse]', 'parameters = ' + vec(THETA_MAX),
        'loglikelihood_2008_2023 = ' + num(ll.group(2)),
        'years = [%s]' % ', '.join(r[0] for r in rows),
        'observations = [%s]' % ', '.join(r[1] for r in rows),
        'annual = ' + vec([float(r[2]) for r in rows]),
        'cumulative = ' + vec([float(r[3]) for r in rows]), '']

# Action 8 on a small grid
axes = dict(v_r_symp='[1000.]', v_beta_1='[0.]', v_S_sat='[90.]', v_C_recover='[1.]',
            v_C_init='[0.0085]', v_gamma='[21.50001]', v_beta_0='[20.,26.]', v_D='[16.,20.]',
            v_kappa='[0.05,0.07]', v_r_allee='[0.]', num_workers='2')
args = ['grid', '--run-dir', 'Simulations/_ref_grid', '--solver', 'exact']
for k, v in axes.items():
    args += ['--config-set', '%s=np.array(%s)' % (k, v) if k != 'num_workers' else 'num_workers=2']
run(*args)
P = np.load(path('_ref_grid/tested_parameters.npy'))
L = np.load(path('_ref_grid/log_likelihood.npy'))
out += ['[grid]', 'beta_0 = ' + vec(P[:, 2]), 'D = ' + vec(P[:, 4]), 'kappa = ' + vec(P[:, 9]),
        'loglikelihood = ' + vec(L), '']

# Action 2, short: 2 iterations of 30 draws of the reduced model. So few draws from Table 2's
# proposal collapse onto one or two, which makes the next covariance singular, so the
# variances here are a hundredth of Table 2's. `fast` agrees with `exact` to about 1e-12.
run('amis', '--run-dir', 'Simulations/_ref_amis', '--solver', 'fast', '--seed', '1',
    '--config-set', 'N_AMIS=2', '--config-set', 'N_L=30', '--config-set', 'num_workers=4',
    '--config-set', 'scale_para_AMIS=np.array([0.,0.,0.03,0.,0.004,0.01,0.,0.,1e-10,1.5e-7])',
    '--config-set', 'parameters_ranges=' + RANGES, '--config-set', 'initial_parameters=' + INIT)
d = path('_ref_amis/')
S = np.load(d + 'sampled_parameters.npy')[:, :, [2, 4, 5, 8, 9]]
lam = np.load(d + 'log_likelihood_times_prior.npy')
w = np.load(d + 'weight.npy')
m = np.load(d + 'mean_proposal.npy')
V = np.load(d + 'var_proposal.npy')
out += ['[amis]', 'iterations = %d' % S.shape[0], 'samples = %d' % S.shape[1]]
out.append('draws = [' + ', '.join(vec(x) for x in S.reshape(-1, 5)) + ']')
out += ['log_target = ' + vec(lam), 'weights = ' + vec(w)]
out.append('means = [' + ', '.join(vec(x) for x in m) + ']')
out.append('covariances = [' + ', '.join(vec(x) for x in V) + ']')
print('\n'.join(out))
for name in ('_ref_rmse', '_ref_grid', '_ref_amis'):
    clean(name)
